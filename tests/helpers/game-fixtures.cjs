function installGameFixtures(context) {
  const runtime = createGameRuntime(context);
  const modules = {};
  for (const [name, [module, property, method]] of Object.entries(api)) {
    const fn = (receiver, ...args) => {
      if (receiver && property in Object(receiver)) {
        return method ? receiver[property](...args) : receiver[property];
      }
      return runtime.load(module)[name](receiver, ...args);
    };
    context[name] = fn;
    (modules[module] ||= {})[name] = fn;
  }
  const originalRequire = context.require;
  context.require = (name, ...args) => {
    const match = name.match(/(?:^|\/)game\/(\w+)$/);
    return match ? modules[match[1]] : originalRequire ? originalRequire(name, ...args) : {};
  };
  return context;
}
module.exports = {installGameFixtures};
